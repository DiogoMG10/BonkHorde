"""Blender side of the Wardwood art kit (M3.B).

    "$BLENDER" -b -P tools/art/kit.py -- [--no-blend] [--no-glb]

Builds every asset in tools/art/assets.py as Blender objects (one object per
colour part, authored normals as custom split normals, a plain principled
material per colour) and writes:

  assets/art/wardwood_kit.blend        the editable source, one collection per asset
  assets/art/export/<Asset>.glb        Roblox-importable meshes (3D Importer / Open Cloud)
  src/server/Wardwood/ArtMeshes/<Asset>.luau
                                       the same geometry packed for the game, which
                                       builds it at runtime (EditableMesh), no upload
  assets/art/manifest.json             triangles, parts, colours and sizes per asset

Coordinates: Blender is Z up, Roblox Y up; a point (x, y, z) becomes
(x, z, -y), a rotation (determinant +1), so triangle winding is kept.
"""

from __future__ import annotations

import base64
import json
import os
import struct
import sys

import bpy

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)

import assets as kitdef  # noqa: E402

ARGS = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []


def srgb_to_linear(c):
    c = c / 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def material(name, color):
    m = bpy.data.materials.get(name)
    if m:
        return m
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    bsdf = m.node_tree.nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = (*[srgb_to_linear(c) for c in color], 1)
    bsdf.inputs["Roughness"].default_value = 0.85
    m.diffuse_color = (*[srgb_to_linear(c) for c in color], 1)
    return m


def to_object(asset, part, coll):
    me = bpy.data.meshes.new(f"{asset.name}.{part.name}")
    # corners unshared: a two-sided leaf's back face reuses its front's vertices,
    # which a Blender mesh may not hold twice
    corners = [part.pos[i] for tri in part.tris for i in tri]
    me.from_pydata(corners, [], [(3 * k, 3 * k + 1, 3 * k + 2) for k in range(len(part.tris))])
    me.update()
    for poly in me.polygons:
        poly.use_smooth = True
    loops = []
    for poly, nrms in zip(me.polygons, part.nrm):
        # from_pydata keeps each face's corner order, so the authored normals line up
        for k in range(poly.loop_total):
            loops.append(nrms[k])
    me.normals_split_custom_set(loops)
    me.materials.append(material(f"{asset.name}.{part.name}", part.color))
    ob = bpy.data.objects.new(f"{asset.name}.{part.name}", me)
    ob["roblox_color"] = list(part.color)
    ob["roblox_material"] = part.material
    coll.objects.link(ob)
    return ob


# ------------------------------------------------------------------ packing for the game


def pack(part):
    """Roblox space, (position, normal) pairs deduplicated, quantised:
    vertex = 3 x uint16 position over the part's box + 3 x int8 normal,
    triangle = 3 x uint16. Little endian, base64."""
    verts, index = [], {}
    tris = []
    for tri, nrms in zip(part.tris, part.nrm):
        out = []
        for vi, n in zip(tri, nrms):
            x, y, z = part.pos[vi]
            p = (x, z, -y)
            q = (n[0], n[2], -n[1])
            qn = tuple(max(-127, min(127, round(c * 127))) for c in q)
            key = (round(p[0], 4), round(p[1], 4), round(p[2], 4), qn)
            if key not in index:
                index[key] = len(verts)
                verts.append((p, qn))
            out.append(index[key])
        tris.append(out)
    lo = [min(v[0][i] for v in verts) for i in range(3)]
    hi = [max(v[0][i] for v in verts) for i in range(3)]
    span = [max(hi[i] - lo[i], 1e-4) for i in range(3)]
    buf = bytearray()
    for p, qn in verts:
        buf += struct.pack("<HHHbbb", *[round((p[i] - lo[i]) / span[i] * 65535) for i in range(3)], *qn)
    for t in tris:
        buf += struct.pack("<HHH", *t)
    assert len(verts) < 65536
    return {
        "verts": len(verts),
        "tris": len(tris),
        "min": lo,
        "max": hi,
        "data": base64.b64encode(bytes(buf)).decode("ascii"),
    }


def luau_number(x):
    return f"{x:.4f}".rstrip("0").rstrip(".") if "." in f"{x:.4f}" else f"{x}"


def write_luau(asset, packed, path):
    lines = [
        "--!strict",
        f"-- {asset.name}: generated by tools/art/kit.py from tools/art/assets.py. Do not edit;",
        "-- change the recipe and rerun the kit. Server/Wardwood/ArtKit builds it.",
        "return {",
        f'\tname = "{asset.name}",',
        "\tparts = {",
    ]
    for name, pk in packed:
        part = asset.parts[name]
        lo = ", ".join(luau_number(v) for v in pk["min"])
        hi = ", ".join(luau_number(v) for v in pk["max"])
        lines += [
            "\t\t{",
            f'\t\t\tname = "{name}",',
            f"\t\t\tcolor = {{ {part.color[0]}, {part.color[1]}, {part.color[2]} }},",
            f'\t\t\tmaterial = "{part.material}",',
            f"\t\t\tverts = {pk['verts']},",
            f"\t\t\ttris = {pk['tris']},",
            f"\t\t\tmin = {{ {lo} }},",
            f"\t\t\tmax = {{ {hi} }},",
            f'\t\t\tdata = "{pk["data"]}",',
            "\t\t},",
        ]
    lines += ["\t},", "}", ""]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


# ------------------------------------------------------------------ main


def main():
    bpy.ops.wm.read_factory_settings(use_empty=True)
    kit = kitdef.build_all()
    art = os.path.join(ROOT, "assets", "art")
    exp = os.path.join(art, "export")
    luau_dir = os.path.join(ROOT, "src", "server", "Wardwood", "ArtMeshes")
    os.makedirs(exp, exist_ok=True)
    os.makedirs(luau_dir, exist_ok=True)
    manifest = {"source": "tools/art/assets.py", "blend": "assets/art/wardwood_kit.blend", "assets": {}}
    x = 0.0
    for asset in kit:
        coll = bpy.data.collections.new(asset.name)
        bpy.context.scene.collection.children.link(coll)
        lo, hi = asset.bounds()
        objs = []
        for part in asset.parts.values():
            if len(part) == 0:
                continue
            objs.append(to_object(asset, part, coll))
        # lay the kit out in a row in the .blend, so it opens as a line-up
        w = hi[0] - lo[0]
        for ob in objs:
            ob.location.x = x - lo[0]
        x += w + 6
        packed = [(p.name, pack(p)) for p in asset.parts.values() if len(p) > 0]
        write_luau(asset, packed, os.path.join(luau_dir, f"{asset.name}.luau"))
        manifest["assets"][asset.name] = {
            "tris": asset.tris(),
            "size_studs": [round(hi[0] - lo[0], 2), round(hi[2] - lo[2], 2), round(hi[1] - lo[1], 2)],
            "parts": {p.name: {"tris": len(p), "color": list(p.color), "material": p.material}
                      for p in asset.parts.values() if len(p) > 0},
            "glb": f"assets/art/export/{asset.name}.glb",
            "luau": f"src/server/Wardwood/ArtMeshes/{asset.name}.luau",
        }
        if "--no-glb" not in ARGS:
            bpy.ops.object.select_all(action="DESELECT")
            for ob in objs:
                ob.select_set(True)
                saved = ob.location.x
                ob.location.x = 0
                ob["_x"] = saved
            bpy.context.view_layer.objects.active = objs[0]
            bpy.ops.export_scene.gltf(filepath=os.path.join(exp, f"{asset.name}.glb"), use_selection=True,
                                      export_format="GLB", export_yup=True, export_normals=True,
                                      export_apply=False, export_materials="EXPORT")
            for ob in objs:
                ob.location.x = ob["_x"]
                del ob["_x"]
        print(f"[kit] {asset.name}: {asset.tris()} tris, {len(objs)} parts")
    with open(os.path.join(art, "manifest.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=1)
    if "--no-blend" not in ARGS:
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(art, "wardwood_kit.blend"), compress=True)
    print("[kit] done")


main()
